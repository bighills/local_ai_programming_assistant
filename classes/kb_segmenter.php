    /** @var int 最大词长 */
    const MAX_WORD_LEN = 4;

    /**
     * 分词入口
     *
     * 算法流程：
     * 1. 优先使用 4→3→2 字词典匹配（正向最大匹配，FMM）
     * 2. 未被词典覆盖的位置提取重叠二元组（bigram），大幅提高召回率
     * 3. 补充单字专业术语（栈、堆、树等）
     * 4. 滤除停用词和过短碎片
     *
     * 二元组回退解决了以下关键问题：
     * - MySQL FULLTEXT 无法正确识别中文词边界
     * - 查询词中的未见词（OOV）仍能通过字符级匹配对齐
     * - "什么是二叉树" → 词典命中"二叉树"，剩余"什么"被过滤，
     *   "什么是"的二元组"什么""么是"也被去除，不会干扰 BM25 评分
     *
     * @param string $text 待分词文本
     * @return array 分词结果（有意义的关键词）
     */
    public static function segment(string $text): array {
        self::load_dictionary();
        $stopwords = self::get_stopwords();
        $single = self::get_single_terms();

        $len = mb_strlen($text, 'UTF-8');
        $pos = 0;
        $covered = []; // 追踪被词典覆盖的字符位置
        $words = [];

        // Phase 1: 正向最大匹配（FMM） + 记录覆盖位置
        while ($pos < $len) {
            $matched = false;
            for ($l = self::MAX_WORD_LEN; $l >= 2; $l--) {
                if ($pos + $l > $len) {
                    continue;
                }
                $word = mb_substr($text, $pos, $l, 'UTF-8');
                if (isset(self::$dictionary[$l][$word])) {
                    $words[] = $word;
                    for ($j = 0; $j < $l; $j++) {
                        $covered[$pos + $j] = true;
                    }
                    $pos += $l;
                    $matched = true;
                    break;
                }
            }
            if (!$matched) {
                $pos++;
            }
        }

        // Phase 2: 从未被词典覆盖的连续字符段提取重叠二元组
        // 仅从连续未覆盖的字符段内提取二元组，而非"任一位置未覆盖"即提取。
        // 原实现会产生跨词边界噪声：如"二叉树的遍历"中"二叉树"已被词典覆盖(0-2)、
        // "的"未覆盖(3)、"遍历"已被覆盖(4-5)，原条件(!isset($covered[$i]) || !isset($covered[$i+1]))
        // 会提取"树的"(2,3)、"的遍"(3,4)等跨词边界噪声二元组，污染 BM25 索引和评分。
        // 新实现只在连续未覆盖段(长度≥2)内提取二元组，消除跨词边界噪声，
        // 同时保留对未登录词(OOV)的召回能力：如"大语言模型"全部未覆盖时仍能提取"大语""语言"等二元组。
        $runstart = -1;
        for ($i = 0; $i <= $len; $i++) {
            $uncovered = ($i < $len) && !isset($covered[$i]);
            if ($uncovered) {
                if ($runstart < 0) {
                    $runstart = $i;
                }
            } else {
                if ($runstart >= 0 && ($i - $runstart) >= 2) {
                    // 从这段连续未覆盖的字符中提取重叠二元组
                    for ($j = $runstart; $j < $i - 1; $j++) {
                        $bigram = mb_substr($text, $j, 2, 'UTF-8');
                        if (!isset($stopwords[$bigram])) {
                            $words[] = $bigram;
                        }
                    }
                }
                $runstart = -1;
            }
        }

        // Phase 3: 补充单字专业术语
        foreach ($single as $char => $_) {
            if (mb_strpos($text, $char, 0, 'UTF-8') !== false) {
                $words[] = $char;
            }
        }

        // 最终去重 + 停用词过滤
        $result = [];
        foreach ($words as $w) {
            $w = trim($w);
            if (mb_strlen($w, 'UTF-8') < 2 && !isset($single[$w])) {
                continue;
            }
            if (isset($stopwords[$w])) {
                continue;
            }
            $result[$w] = true;
        }

        return array_keys($result);
    }

