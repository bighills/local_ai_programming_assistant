 * AI 编程助手 - 中文分词器
 *
 * 基于词典 + 正向最大匹配（FMM）算法的轻量级中文分词器，
 * 专为编程教育领域的知识库关键词提取优化。
 *
 * 词典覆盖：
 * - 编程语言、数据结构的专业技术术语
 * - 计算机科学核心概念
 * - 常见教学用语
 * - 通用中文常用词汇
 *
 * 算法（v2 - 带二元组回退）：
 * 1. 优先使用 4→3→2 字词典匹配（正向最大匹配，FMM），记录覆盖位置
 * 2. 未被词典覆盖的位置提取重叠二元组（bigram），大幅提高召回率
 * 3. 补充单字专业术语（栈、堆、树等）
 * 4. 滤除停用词和过短碎片
 *
 * 二元组回退解决中文 OOV（未登录词）问题："大语言模型"虽不在词典中，
 * 但"大语""语言""言模""模型"等二元组仍能与文档中的"大语言模型"字符级对齐。
 *
 * @package    local_ai_programming_assistant
 */
